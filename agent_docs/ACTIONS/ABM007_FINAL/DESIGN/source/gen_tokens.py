"""Generates ABM007_FINAL's token stylesheet from the approved hex anchors.
Hex anchors are converted to HSL with enough precision that a browser resolves each one back to
the exact approved 8-bit color. Aliases reference the anchors with var(), so an alias can never drift.
Usage: python3 gen_tokens.py <DESIGN dir>"""
import sys, colorsys, pathlib
def hsl(hexv):
    h=hexv.lstrip('#'); r,g,b=[int(h[i:i+2],16)/255 for i in (0,2,4)]
    H,L,S=colorsys.rgb_to_hls(r,g,b)
    f=lambda x: ('%.10f'%x).rstrip('0').rstrip('.')
    return f"{f(H*360)} {f(S*100)}% {f(L*100)}%"
